"""Golden briefs: one per archetype, each with the slots it must produce and a golden ``APP_SPEC.md``.

Layout (``evals/datasets/briefs/<id>/``)::

    brief.yaml          the input: archetype, mode, policy, the opening message
    expected.yaml       what the session must produce: slots, screens, flows, data, counts
    APP_SPEC.md.golden  the spec exactly as the real engines render it in mock mode

``expected.yaml`` and the golden are GENERATED by ``python -m evals.runners.make_goldens`` (and
checked by ``tests/e2e/test_goldens.py``); review the diff before committing a regeneration.
The golden is not named ``*.md`` on purpose: markdown lives under ``docs/`` only.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

import yaml

from evals.harness.journeys import Journey, JourneyResult
from mde_contracts.common import Mode
from mde_contracts.records import SessionRecord, SpecVersionRecord

DATASETS = Path(__file__).resolve().parents[1] / "datasets"
BRIEFS = DATASETS / "briefs"
GOLDEN_NAME = "APP_SPEC.md.golden"


@dataclass(frozen=True)
class GoldenBrief:
    id: str
    title: str
    archetype: str
    mode: Mode
    policy: str | None
    opening: str
    directory: Path

    @property
    def journey(self) -> Journey:
        return Journey(
            name=self.id,
            archetype=self.archetype,
            opening=self.opening,
            mode=self.mode,
            policy_id=self.policy,
        )

    @property
    def golden_path(self) -> Path:
        return self.directory / GOLDEN_NAME

    @property
    def expected_path(self) -> Path:
        return self.directory / "expected.yaml"


def load_briefs(root: Path = BRIEFS) -> list[GoldenBrief]:
    out: list[GoldenBrief] = []
    for path in sorted(root.glob("*/brief.yaml")):
        raw = cast("dict[str, Any]", yaml.safe_load(path.read_text(encoding="utf-8")))
        out.append(
            GoldenBrief(
                id=str(raw["id"]),
                title=str(raw["title"]),
                archetype=str(raw["archetype"]),
                mode=cast("Mode", raw.get("mode", "guided")),
                policy=raw.get("policy"),
                opening=str(raw["opening"]),
                directory=path.parent,
            )
        )
    return out


def expected_of(session: SessionRecord, spec: SpecVersionRecord) -> dict[str, Any]:
    """The comparable facts of a session: slots, screens, flows, data and counts."""
    slots = {
        sid: {"value": rec.value, "state": rec.state}
        for sid, rec in sorted(session.discovery.slots.items())
        if rec.value not in (None, "", [])
    }
    s = spec.spec
    return {
        "slots": slots,
        "screens": [
            {"id": x.id, "route": x.route, "recipe": x.recipe, "surface": x.surface, "auth": x.auth}
            for x in s.screens
        ],
        "flows": [{"id": f.id, "name": f.name, "screens": list(f.screens)} for f in s.flows],
        "entities": [e.id for e in s.data.entities],
        "operations": [o.id for o in s.api.operations],
        "roles": [r.id for r in s.roles.roles],
        "counts": {
            "screens": len(s.screens),
            "flows": len(s.flows),
            "entities": len(s.data.entities),
            "operations": len(s.api.operations),
        },
    }


def dump_expected(data: dict[str, Any]) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def result_expected(result: JourneyResult, session: SessionRecord) -> dict[str, Any]:
    return expected_of(session, result.spec)
