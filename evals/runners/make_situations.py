"""Generate ``evals/datasets/situations/situations.yaml``: the situation catalog as data.

    uv run python -m evals.runners.make_situations           # rewrite the dataset
    uv run python -m evals.runners.make_situations --check   # exit 1 if it differs from the spec

The rows come straight from section 9 of ``docs/product/context-engine-spec.md`` and each row is
linked to its scenario file under ``tests/scenarios``.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from evals.harness.catalog import ROOT, parse_situation_table
from evals.runners._io import say

OUT = ROOT / "evals" / "datasets" / "situations" / "situations.yaml"
SCENARIOS = ROOT / "tests" / "scenarios"


def build() -> str:
    rows = []
    for row in parse_situation_table():
        files = sorted(SCENARIOS.glob(f"{row.sit_id}-*.yaml"))
        rows.append(
            {
                "id": row.sit_id,
                "situation": row.situation,
                "detection": row.detection,
                "behavior": row.behavior,
                "scenario": f"tests/scenarios/{files[0].name}" if files else None,
            }
        )
    header = (
        "# The situation catalog (spec section 9) as data. Generated by\n"
        "# `python -m evals.runners.make_situations`; do not edit by hand.\n"
    )
    return header + yaml.safe_dump(
        {"situations": rows}, sort_keys=False, allow_unicode=True, width=100
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the situations dataset")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = build()
    current = OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") if OUT.exists() else None
    if args.check:
        if current != text:
            say(f"{OUT} is out of date: run python -m evals.runners.make_situations")
            return 1
        return 0
    Path(OUT).parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    say(f"wrote {OUT} ({len(parse_situation_table())} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
