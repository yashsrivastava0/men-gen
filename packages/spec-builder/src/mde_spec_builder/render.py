"""Deterministic renderer: ``AppSpec`` -> ``APP_SPEC.md`` (B9).

Same input, same bytes. The file is Markdown for people plus fenced YAML blocks for machines
(```` ```yaml id=SCR-014 kind=screen ````), in the fixed section order of ``SECTION_ORDER``:

    front matter (HEADER) / title / section table, then ``## 1. Summary`` ... ``## 15. Revision``.

The hash rule (normative, implemented in ``mde_spec_loader.hashing``): ``header.hash`` is the sha256
of the whole text (UTF-8, LF) with the front-matter line ``hash: "<hex>"`` blanked to ``hash: ""``.
``render_spec`` ignores whatever ``spec.header.hash`` holds and embeds the computed value, so the
hash is a pure function of the content. The file holds no timestamps and no random ids.

Canonical YAML rules live in ``mde_spec_loader.codec`` (declared field order, defaults and Nones
omitted, free-form maps key-sorted, three renames: ``texts`` -> ``copy``, ``source`` -> ``from``,
``schema_id`` -> ``schema``).
"""

from __future__ import annotations

from collections.abc import Sequence

from pydantic import BaseModel

from mde_contracts.spec import SECTION_ORDER, SINGLETON_BLOCK_IDS, AppSpec, SpecHeader
from mde_spec_loader.codec import BacklogBlock, block_data, dump_yaml
from mde_spec_loader.fragments import fenced
from mde_spec_loader.hashing import compute_spec_hash, embed_hash, verify_hash
from mde_spec_loader.parse import escape_summary
from mde_spec_loader.tokens import estimate_tokens

SECTION_TITLES: dict[str, str] = {
    "header": "Header and index",
    "summary": "Summary",
    "app": "App",
    "design": "Design",
    "navigation": "Navigation",
    "data": "Data",
    "api": "API",
    "roles": "Roles",
    "integrations": "Integrations",
    "behavior": "Behavior",
    "screens": "Screens",
    "flows": "Flows",
    "build_sequence": "Build sequence",
    "acceptance": "Acceptance",
    "assumptions": "Assumptions and sources",
    "revision": "Revision",
}

_NOTICE = (
    "> Generated by the Context Engine and read-only: change the app through the conversation, "
    "never by editing this file. Blocks are fenced YAML; each fence carries `id` and `kind`."
)


def _oneline(text: str) -> str:
    return " ".join(text.split())


def _block(block_id: str, kind: str, model: BaseModel) -> str:
    return fenced(block_id, kind, dump_yaml(block_data(kind, model)))


def _front_matter(header: SpecHeader, hash_value: str) -> str:
    """The front-matter block, ``---`` fences included, ending with a newline."""
    first: dict[str, object] = {
        "spec_version": header.spec_version,
        "schema": header.schema_id,
        "app_id": header.app_id,
        "mode": header.mode,
        "stack_profile": header.stack_profile,
        "inherits": list(header.inherits),
        "language": header.language,
    }
    tail: dict[str, object] = {"brief_hash": header.brief_hash}
    if header.research_note_hash is not None:
        tail["research_note_hash"] = header.research_note_hash
    # dump_yaml output ends with its own newline
    return "---\n" + dump_yaml(first) + f'hash: "{hash_value}"\n' + dump_yaml(tail) + "---\n"


def _id_range(ids: Sequence[str]) -> str:
    if not ids:
        return "-"
    if len(ids) == 1:
        return ids[0]
    return f"{ids[0]}..{ids[-1]} ({len(ids)})"


def _section(number: int, key: str, body: str) -> str:
    return f"## {number}. {SECTION_TITLES[key]}\n\n{body}\n\n"


def _collection(items: Sequence[tuple[str, str, str]]) -> str:
    """Screen/flow blocks, each under a ``###`` line: (id, label, fenced block)."""
    if not items:
        return "None."
    return "\n\n".join(
        f"### {item_id} - {_oneline(label)}\n\n{block}" for item_id, label, block in items
    )


def _sections(spec: AppSpec) -> tuple[list[str], dict[str, str]]:
    """Section texts for numbers 1..15 and the ids column of the section table."""
    screens = [(s.id, s.route, _block(s.id, "screen", s)) for s in spec.screens]
    flows = [(f.id, f.name, _block(f.id, "flow", f)) for f in spec.flows]
    assumptions = _block("ASSUME", "assumptions", spec.assumptions)
    if spec.backlog:
        assumptions += "\n\n" + _block("BACKLOG", "backlog", BacklogBlock(items=spec.backlog))
    bodies: dict[str, str] = {
        "summary": escape_summary(spec.summary),
        "app": _block("APP", "app", spec.app),
        "design": _block("DESIGN", "design", spec.design),
        "navigation": _block("NAV", "navigation", spec.navigation),
        "data": _block("DATA", "data", spec.data),
        "api": _block("API", "api", spec.api),
        "roles": _block("ROLES", "roles", spec.roles),
        "integrations": _block("INTEGRATIONS", "integrations", spec.integrations),
        "behavior": _block("BEHAVIOR", "behavior", spec.behavior),
        "screens": _collection(screens),
        "flows": _collection(flows),
        "build_sequence": _block("BUILD", "build_sequence", spec.build),
        "acceptance": _block("ACCEPT", "acceptance", spec.acceptance),
        "assumptions": assumptions,
        "revision": _block("REV", "revision", spec.revision),
    }
    ids: dict[str, str] = {
        key: SINGLETON_BLOCK_IDS[key] for key in SECTION_ORDER if key in SINGLETON_BLOCK_IDS
    }
    ids["summary"] = "SUMMARY"
    ids["screens"] = _id_range([s.id for s in spec.screens])
    ids["flows"] = _id_range([f.id for f in spec.flows])
    if spec.backlog:
        ids["assumptions"] = "ASSUME, BACKLOG"
    texts = [
        _section(number, key, bodies[key]) for number, key in enumerate(SECTION_ORDER) if number
    ]
    texts[-1] = texts[-1].rstrip("\n") + "\n"
    return texts, ids


def _assemble(spec: AppSpec, hash_value: str) -> str:
    sections, ids = _sections(spec)
    sizes = [estimate_tokens(text) for text in sections]
    blank_front = _front_matter(spec.header, "")
    header_tokens = estimate_tokens(blank_front[:-1])  # the block without its trailing newline
    rows = ["| # | Section | Ids | ~Tokens |", "| --- | --- | --- | --- |"]
    rows.append(f"| 0 | {SECTION_TITLES['header']} | HEADER | {header_tokens} |")
    for number, key in enumerate(SECTION_ORDER):
        if number:
            rows.append(f"| {number} | {SECTION_TITLES[key]} | {ids[key]} | {sizes[number - 1]} |")
    head = (
        _front_matter(spec.header, hash_value)
        + f"\n# {_oneline(spec.app.name)} - APP_SPEC\n\n{_NOTICE}\n\n"
        + f"## 0. {SECTION_TITLES['header']}\n\n"
        + "\n".join(rows)
        + "\n\n"
    )
    return head + "".join(sections)


# --------------------------------------------------------------------------- public API


def render_unhashed(spec: AppSpec) -> str:
    """The rendered file with ``hash: ""`` (the exact text the hash is computed over)."""
    return _assemble(spec, "")


def render_spec(spec: AppSpec) -> str:
    """Render ``spec`` to ``APP_SPEC.md`` text with its sha256 embedded in the front matter."""
    return embed_hash(render_unhashed(spec))


def spec_hash(spec: AppSpec) -> str:
    """The hash ``render_spec(spec)`` embeds (equals ``BuildResult.spec_hash``)."""
    return compute_spec_hash(render_unhashed(spec))


def with_rendered_hash(spec: AppSpec) -> AppSpec:
    """``spec`` with ``header.hash`` set to its rendered hash, so ``parse(render(s)) == s``."""
    header = spec.header.model_copy(update={"hash": spec_hash(spec)})
    return spec.model_copy(update={"header": header})


