@case("spc-fe-10")
def test_fe_10_a_consumer_with_a_larger_window_gets_fewer_tasks_and_the_same_content():
    g = make_graph("small")
    default = pack_of(g)
    first = next(t for t in default.tasks if t["wave"] == "W3" and len(t["reads"]["screens"]) >= 3)
    narrow = pack_of(g, task_read_budget=first["read_tokens"]["total"] - 1500)
    wide = pack_of(g, task_read_budget=60_000, consumer_id="large-context-default")
    assert wide.manifest["task_read_budget"] == 60_000 > default.manifest["task_read_budget"]
    assert (
        len(wide.tasks) <= len(default.tasks) < len(narrow.tasks)
    )  # the wider the window, the fewer tasks
    assert wide.content_hash == default.content_hash == narrow.content_hash
    for path in default.files:
        if path.startswith(("screens/", "global/")) and path != "global/needs.json":
            assert default.files[path] == wide.files[path] == narrow.files[path]


