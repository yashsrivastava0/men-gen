@case("spc-fe-01")
def test_fe_01_a_fact_missing_from_a_slice_is_stopped_by_v27_and_the_lookup_limit_is_three():
    g = make_graph("small")
    p = pack_of(g)
    assert not [
        f for f in findings_of(g, p) if f.severity == "blocker"
    ]  # the clean graph passes everything
    s = live_screen(g)
    ent = next(b.split(".")[0] for r in s.regions for b in r.bind if b.split(".")[0] in g.entities)
    del g.entities[ent]  # mut: the fact the slice needs is gone
    found = findings_of(g, None, only={"V-27"})
    assert any(f.code == "V-27" and f.severity == "blocker" and f.where == s.id for f in found)
    assert any("unresolved" in f.why for f in found)
    assert (
        CFG.scope.lookups_before_raise == 3
    )  # at run time: at most three lookups, then a raised decision
    assert "raise_decision" in p.files["AGENTS.md"]


