@case("spc-fe-11")
def test_fe_11_direction_axes_differ_per_app_so_the_output_is_not_a_look_alike(tmp_path):
    import random

    from edge_support.eb_run import Rig

    from mde_spec_core import tokens

    a = tokens.pick_directions(3, rnd=random.Random(1))
    b = tokens.pick_directions(3, rnd=random.Random(2))
    for picks in (a, b):
        assert tokens.check_direction_set(picks, brand_locked=False) == []
        assert len({p["mood_family"] for p in picks}) > 1
    assert a != b  # another app, another set
    sets = {}
    for key in ("quick", "standard"):
        rig = Rig(tmp_path, key, tag=key)
        assert rig.go("plan", "design").status == "awaiting_g2"
        sets[key] = sorted(
            (d.mood, d.shape, d.density, d.motion_personality, d.seed_hue)
            for d in rig.ctx.graph.directions.values()
        )
        assert sets[key]
    assert sets["quick"] != sets["standard"]  # two real apps do not get the same look


