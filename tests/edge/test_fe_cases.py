@case("spc-fe-02")
def test_fe_02_task_cards_own_disjoint_files_and_the_shared_files_are_generated_by_code():
    for name in ("small", "big", "program"):
        p = pack_of(make_graph(name))
        owned = [path for t in p.tasks for path in t["owns"]]
        assert len(owned) == len(set(owned)), name  # no two workers own one file
        shared = ("global/tokens.dtcg.json", "global/routes.json", "contract/openapi.yaml")
        assert all(f in p.files for f in shared)  # generated by code, in the pack
        assert not [o for o in owned if any(s.split("/")[-1].split(".")[0] in o for s in shared)]
        assert all(o.startswith("app/") for o in owned)  # a worker owns only its own app's folders


