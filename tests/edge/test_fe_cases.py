@case("spc-fe-07")
def test_fe_07_a_task_over_the_budget_is_split_and_a_heavy_screen_travels_alone():
    from mde_spec_core.pack import PackBreach

    g = make_graph("small")
    base = pack_of(g)
    first = next(t for t in base.tasks if t["wave"] == "W3" and len(t["reads"]["screens"]) >= 3)
    tight = first["read_tokens"]["total"] - 1500  # a budget the three-screen task no longer fits
    split = pack_of(g, task_read_budget=tight)
    assert split.budget_report["tasks_over_budget"] == []
    assert len(split.tasks) > len(base.tasks)  # the packager splits instead of overrunning
    assert all(t["read_tokens"]["total"] <= tight for t in split.tasks)
    # the smallest budget the packager accepts: the heaviest screen's own task fills it, so it travels alone
    lo, hi = 5_000, tight
    failed_codes: list[str] = []
    while hi - lo > 50:
        mid = (lo + hi) // 2
        try:
            pack_of(g, task_read_budget=mid)
            hi = mid
        except PackBreach as exc:
            failed_codes.append(exc.error["code"])  # reported loudly, never truncated
            lo = mid
    assert set(failed_codes) == {"TASK_OVER_BUDGET"}
    floor_pack = pack_of(g, task_read_budget=hi)
    alone = [t for t in floor_pack.tasks if t["wave"] == "W3" and len(t["reads"]["screens"]) == 1]
    assert alone and max(t["read_tokens"]["total"] for t in alone) >= hi - 400


